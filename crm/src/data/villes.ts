/* ── Normalisation : casse, accents, tirets, espaces ── */
export function normalizeCity(s: string): string {
  return (s || "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")   // accents
    .replace(/[’'`´\-–—_]/g, " ")       // tirets & apostrophes
    .replace(/\s+/g, " ");
}

