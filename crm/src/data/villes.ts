/* ── Prix d'une ville (null si ville inconnue) ── */
export function priceForCity(name: string, villes: Ville[]): number | null {
  const norm = normalizeCity(name);
  if (!norm) return null;
  const target = CITY_ALIASES[norm] || norm;
  const hit = villes.find((v) => {
    const n = normalizeCity(v.nom);
    return n === target || CITY_ALIASES[n] === target;
  });
  return hit ? hit.prix : null;
}

/* ── Persistance + synchronisation entre les pages ── */
let cache: Ville[] | null = null;
const listeners = new Set<() => void>();

function loadFromStorage(): Ville[] {
  try {
    const s = localStorage.getItem(VILLES_KEY);
    if (s) {
      const parsed = JSON.parse(s) as Ville[];
      if (Array.isArray(parsed) && parsed.length) return parsed;
    }
  } catch { /* ignore */ }
  return DEFAULT_VILLES;
}

export function saveVilles(list: Ville[]) {
  cache = list;
  try { localStorage.setItem(VILLES_KEY, JSON.stringify(list)); } catch { /* ignore */ }
  listeners.forEach((l) => l());
}

export function resetVilles() {
  try { localStorage.removeItem(VILLES_KEY); } catch { /* ignore */ }
  cache = null;
  listeners.forEach((l) => l());
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  return () => { listeners.delete(cb); };
}

/** Hook : liste des villes, synchronisée en direct entre toutes les pages */
export function useVilles(): Ville[] {
  return useSyncExternalStore(
    subscribe,
    () => (cache ??= loadFromStorage()),
    () => DEFAULT_VILLES,
  );
}
